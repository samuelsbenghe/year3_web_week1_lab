from http.server import BaseHTTPRequestHandler, HTTPServer
from datetime import datetime
import os
import random
import urllib.parse

# port 80 on linux, 8012 on windows
PORT = 80
if os.name == "nt":
    PORT = 8012

visit_count = 0

greetings = [
    "Hello, World!",
    "Hello, User!",
    "Hello, from Goldsmiths!",
    "Hello, someone other than me!",
    "Roblox sucks!",
]


def random_greeting():
    return random.choice(greetings)


class DynamicHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        global visit_count
        url_params = urllib.parse.urlparse(self.path).query
        param_name = urllib.parse.parse_qs(url_params).get("name", [""])[0]
        visit_count += 1
        user_agent = self.headers.get("User-Agent", "Unknown")
        details = ""
        if os.name == "nt":
            details = "System load not available on Windows"
        else:
            details = os.getloadavg()
        now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        html = f"""<!DOCTYPE html>
<html>
<head><title>Dynamic Page</title></head>
<body>
    <h1>This page is generated by Python!</h1>
    <p>User Agent: {user_agent}</p>
    <p>{random_greeting()}</p>
    <p>Server time: {now}</p>
    <p>System load: {details}</p>
    <p>Visitor count: {visit_count}</p>
</body>
</html>"""
        self.send_response(200)
        self.send_header("Content-type", "text/html; charset=utf-8")
        self.end_headers()
        self.wfile.write(html.encode("utf-8"))


if __name__ == "__main__":
    server = HTTPServer(("0.0.0.0", PORT), DynamicHandler)
    print(f"Serving on 0.0.0.0:{PORT}...")
    server.serve_forever()
